public class Operadores2 {
    public static void main(String[] args) {
        int resultadoEntero = 5 / 2;
double resultadoDecimal = 5.0 / 2;

System.out.println(resultadoEntero);
System.out.println(resultadoDecimal);
    }
    
}
//El resultado cambia porque el tipo de dato define cómo se almacena y representa el valor.
//Un int solo admite enteros, mientras que un double permite decimales.
//Por eso un precio declarado como int se muestra sin decimales, y como double se muestra con decimales.
