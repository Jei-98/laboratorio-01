public class Comparaciones {

    public static void main(String[] args) {
        int edad = 20;

        // Predicción con edad = 20: true, false, true, true, false
        System.out.println(edad > 18);
        System.out.println(edad < 18);
        System.out.println(edad >= 20);
        System.out.println(edad == 20);
        System.out.println(edad != 20);
    }
}
